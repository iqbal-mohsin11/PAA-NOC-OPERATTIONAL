// Helper to convert an AIIAP row into a full AssetItem
export function convertAIIAPRowToAsset(row: AIIAPUpsRow, index: number): AssetItem {
  const assetId = `PAA-UPS-${row.tagNo.replace('UPS-', '')}`;
  const isHealthy = row.backupStatus === 'OK';
  
  // Calculate next replacement (approx 2.5 years after last replacement)
  const lastDate = new Date(row.batteryReplacementDate);
  const nextDate = new Date(lastDate.getTime() + (730 * 24 * 60 * 60 * 1000));
  const nextDateStr = isNaN(nextDate.getTime()) ? '2025-10-21' : nextDate.toISOString().split('T')[0];

  return {
    id: assetId,
    barcode: `10099${row.tagNo.replace('UPS-', '').padStart(4, '0')}`,
    qrCode: `${assetId}|${row.modelNo}|${row.location}-${row.roomNo}|CRN:${row.crnNo}`,
    name: `${row.modelNo} (${row.kvaRating}) - ${row.tagNo}`,
    category: 'UPS',
    department: row.location.includes('Radar') ? 'Radar' : row.location.includes('Cargo') ? 'Cargo' : row.location.includes('Fire') ? 'Fire' : 'IT Infrastructure',
    assignedUser: `Allama Iqbal Int'l Airport (${row.location} - ${row.roomNo})`,
    paaNumber: `PAA/AIIAP/UPS/${row.crnNo}`,
    location: {
      building: 'AIIAP Terminal Complex',
      floor: row.location,
      room: row.roomNo,
    },
    vendorCompany: 'EATON Power Quality / PAA Telecom Source',
    brand: 'EATON',
    model: row.modelNo,
    serialNumber: row.serialNo,
    assetTag: row.tagNo,
    crnNo: row.crnNo,
    purchaseDate: '2020-01-15',
    warrantyExpiry: '2026-12-31',
    status: isHealthy ? 'Active' : 'Under Repair',
    isRemoved: false,
    images: {
      devicePhoto: '/eaton_dx1000.webp',
    },
    upsSpecs: {
      modelNo: row.modelNo,
      capacityKvaKw: row.voltage,
      kvaRating: row.kvaRating,
      kwRating: row.kwRating,
      crnNo: row.crnNo,
      srNo: row.srNo,
      tagNo: row.tagNo,
      voltage: `${row.voltage} (230V AC ±1%, 36V DC Bus)`,
      inputVoltage: '220V/230V AC (160V-290V)',
      outputVoltage: '230V AC ±1% Pure Sine Wave',
      batteryBankVoltage: '36V DC (3 x 12V 7.2Ah)',
      roomNo: row.roomNo,
      locationDetails: `${row.location} - Room ${row.roomNo}`,
      backupTime: row.backupTime,
      backupStatus: row.backupStatus,
      noOfBatteries: row.noOfBatteries,
      batteryType: row.batteryType,
      lastBatteryChangeDate: row.batteryReplacementDate,
      nextBatteryChangeDate: nextDateStr,
      batteryHealthPercent: isHealthy ? (row.batteryReplacementDate >= '2024-01-01' ? 95 : row.batteryReplacementDate >= '2023-01-01' ? 82 : 60) : 15,
      loadPercentage: 55,
    },
    pingStatus: isHealthy ? 'Online' : 'Warning',
    uptime: isHealthy ? '180 days' : '0 days',
    lastMaintenanceDate: row.batteryReplacementDate,
    createdAt: '2020-01-15T10:00:00Z',
    updatedAt: new Date().toISOString(),
  };
}

export const initialAIIAPUpsAssets: AssetItem[] = aiiapUpsRawData.map(convertAIIAPRowToAsset);
